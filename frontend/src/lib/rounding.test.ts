describe("roundHalfEven", () => {
  it("should send an exact half to the even neighbour, where Math.round sends it up", () => {
    expect(roundHalfEven(0.5)).toBe(0);
    expect(roundHalfEven(1.5)).toBe(2);
    expect(roundHalfEven(2.5)).toBe(2);
    expect(roundHalfEven(3.5)).toBe(4);
    expect(roundHalfEven(500.5)).toBe(500);
    expect(Math.round(500.5)).toBe(501);
  });

  it("should mirror Python on negative halves, where Math.round goes toward +Infinity", () => {
    expect(roundHalfEven(-0.5)).toBe(0);
    expect(roundHalfEven(-1.5)).toBe(-2);
    expect(roundHalfEven(-2.5)).toBe(-2);
    expect(roundHalfEven(-3.5)).toBe(-4);
    // Math.round(-0.5) is -0 and Math.round(-1.5) is -1: away from Python twice over.
    expect(Math.round(-1.5)).toBe(-1);
  });

  it("should never answer with negative zero in the one-argument form", () => {
    // Python's one-argument round yields an int, and an int has no signed zero.
    expect(Object.is(roundHalfEven(-0.2), 0)).toBe(true);
    expect(Object.is(roundHalfEven(-0), 0)).toBe(true);
    expect(Object.is(roundHalfEven(-0.5), 0)).toBe(true);
    // The two-argument form yields a float, which does keep the sign.
    expect(Object.is(roundHalfEven(-0.2, 0), -0)).toBe(true);
    expect(Object.is(roundHalfEven(-0.004, 2), -0)).toBe(true);
  });

  it("should decide on the decimal the double really is, not on value times a power of ten", () => {
    // 2.675 as a double is 2.674999999999999822..., below the half, so Python
    // rounds it DOWN. Scaling first destroys that: the product 2.675 * 100
    // rounds UP to exactly 267.5, and 267.5 then reads as a tie that is not one.
    expect(roundHalfEven(2.675, 2)).toBe(2.67);
    expect(2.675 * 100).toBe(267.5);
    expect(Math.round(2.675 * 100) / 100).toBe(2.68);
    // 1.005 is likewise just below the half.
    expect(roundHalfEven(1.005, 2)).toBe(1);
    // 6.125 and 0.125 are exact, so they really are ties and go to the even digit.
    expect(roundHalfEven(6.125, 2)).toBe(6.12);
    expect(roundHalfEven(0.125, 2)).toBe(0.12);
    // 0.135 as a double is 0.13500000000000000888..., just ABOVE the half.
    expect(roundHalfEven(0.135, 2)).toBe(0.14);
  });

  it("should keep whole numbers, zero and very large values untouched", () => {
    expect(roundHalfEven(23, 2)).toBe(23);
    expect(roundHalfEven(0, 2)).toBe(0);
    expect(roundHalfEven(1e21, 2)).toBe(1e21);
    expect(roundHalfEven(Number.MAX_VALUE, 2)).toBe(Number.MAX_VALUE);
    expect(roundHalfEven(Number.MIN_VALUE, 2)).toBe(0);
  });

  it("should refuse a digit count that is not a whole number of decimal places", () => {
    expect(() => roundHalfEven(1.5, -1)).toThrow();
    expect(() => roundHalfEven(1.5, 1.5)).toThrow();
  });

  it("should pass a non-finite value through rather than inventing one", () => {
    expect(roundHalfEven(Number.NaN)).toBeNaN();
    expect(roundHalfEven(Number.POSITIVE_INFINITY)).toBe(Number.POSITIVE_INFINITY);
    expect(roundHalfEven(Number.NEGATIVE_INFINITY, 2)).toBe(Number.NEGATIVE_INFINITY);
  });

  it("should reproduce every sample measured from CPython", () => {
    const wrong = samples
      .filter((s) => !Object.is(roundHalfEven(s.value, s.ndigits), s.expected))
      .map((s) => `${s.source} -> ${roundHalfEven(s.value, s.ndigits)}`);
    expect(wrong.slice(0, 20), `${wrong.length} of ${samples.length} samples disagree`).toEqual([]);
  });

  it("should have been given samples covering both forms, so the sweep above means something", () => {
    expect(samples.length).toBeGreaterThan(1500);
    expect(samples.filter((s) => s.ndigits === undefined).length).toBeGreaterThan(100);
    expect(samples.filter((s) => s.ndigits === 2).length).toBeGreaterThan(300);
    expect(samples.every((s) => Number.isFinite(s.value))).toBe(true);
  });

  it("should agree with its own zero-digit form apart from the sign of zero", () => {
    const wrong = samples
      .filter((s) => roundHalfEven(s.value) !== roundHalfEven(s.value, 0))
      .map((s) => s.source);
    expect(wrong).toEqual([]);
  });

  it("should differ from Math.round only on exact halves", () => {
    const differing = samples
      .filter((s) => s.ndigits === undefined)
      .filter((s) => roundHalfEven(s.value) !== Math.round(s.value))
      .map((s) => s.value);
    expect(differing.length).toBeGreaterThan(0);
    expect(differing.every((v) => v - Math.floor(v) === 0.5)).toBe(true);
  });
});
